// Read-only aggregation for the Profit dashboard (Req 10-11, 15). Unlike
// every other queries/*.ts file, this one never writes: it only rolls up
// rows already written by purchases.ts/parts.ts/sales.ts into one
// per-Purchase profit figure, computed entirely in SQL (one GROUP BY plus
// joins) rather than fetching Parts/Sales per Purchase — the same
// single-shared-DuckDB-connection lesson documented on
// listPurchasesWithListingSummary: fanning out a query per row broke under
// concurrent statements once there were more than a couple of rows.
import type { DuckDBValue } from '@duckdb/node-api';
import { getConnection } from '../client.js';
import { toNumber } from '../sqlHelpers.js';
import type { PurchaseStatus } from '@pc-parts-flipper/shared';

/** Columns the Profit dashboard can sort by (Req 11). */
export type ProfitSortBy = 'netProfit' | 'pricePaid' | 'purchaseDate';

/** Sort direction for the Profit dashboard (Req 11). */
export type ProfitSortDir = 'asc' | 'desc';

/** Filter/sort/pagination options for the Profit dashboard (Req 10-11, 15). */
export interface ListProfitOptions {
  status?: PurchaseStatus;
  // `true` restricts to Purchases still running (at least one Part not yet
  // sold/unsellable); `false` restricts to Purchases where every Part has
  // resolved. Undefined applies no partial/final filter.
  partial?: boolean;
  sortBy?: ProfitSortBy;
  sortDir?: ProfitSortDir;
  limit?: number;
  offset?: number;
}

/**
 * Per-Purchase profit rollup (Req 10): price paid, realized sale revenue,
 * fees/shipping across those sales, and the resulting net profit. Per-part
 * cost is never allocated (assumption A1) — every figure here lives at the
 * Purchase/lot level only.
 */
export interface PurchaseProfit {
  purchaseId: string;
  listingId: string;
  listingTitle: string;
  status: PurchaseStatus;
  pricePaid: number;
  purchaseDate: string;
  saleRevenue: number;
  feesAndShipping: number;
  netProfit: number;
  totalParts: number;
  partsResolved: number;
  // false ("partial"/running) until every Part generated by this Purchase's
  // teardown is either sold or unsellable. A Purchase with zero Parts (not
  // yet torn down) is also "partial" — nothing has resolved yet, so it
  // cannot be final. An `unsellable` Part counts as resolved: it will never
  // sell, so waiting on it forever would make a dead lot permanently
  // "partial" — documented reasonable choice per the task's own prompt.
  isFinal: boolean;
}

// Maps a ProfitSortBy value to the real SQL column on the `profit` CTE
// built in listProfitByPurchase/countProfitByPurchase below. Interpolated
// directly into the query string (ORDER BY columns can't be bound
// parameters), so this is a strict allow-list rather than passing the
// caller's string straight through.
const SORT_COLUMN: Record<ProfitSortBy, string> = {
  netProfit: 'net_profit',
  pricePaid: 'price_paid',
  purchaseDate: 'purchase_date',
};

// Converts one raw JSON row from the `profit` CTE (see buildProfitCte) into
// the camelCase PurchaseProfit shape.
function mapRow(row: Record<string, unknown>): PurchaseProfit {
  return {
    purchaseId: row.id as string,
    listingId: row.listing_id as string,
    listingTitle: row.listing_title as string,
    status: row.status as PurchaseStatus,
    pricePaid: toNumber(row.price_paid as string),
    purchaseDate: row.purchase_date as string,
    saleRevenue: toNumber(row.sale_revenue as string),
    feesAndShipping: toNumber(row.fees_and_shipping as string),
    netProfit: toNumber(row.net_profit as string),
    totalParts: Number(row.total_parts),
    partsResolved: Number(row.parts_resolved),
    isFinal: row.is_final as boolean,
  };
}

// Builds the shared `profit` CTE (one row per Purchase, aggregated across
// its Parts and their Sales) plus the WHERE clause/params for the given
// filters. Shared by listProfitByPurchase and countProfitByPurchase so the
// two queries can never drift on what counts as a match.
function buildProfitQuery(options?: Pick<ListProfitOptions, 'status' | 'partial'>): {
  cteSql: string;
  whereSql: string;
  params: Record<string, DuckDBValue>;
} {
  const conditions: string[] = [];
  const params: Record<string, DuckDBValue> = {};
  if (options?.status !== undefined) {
    conditions.push('status = $status');
    params.status = options.status;
  }
  if (options?.partial !== undefined) {
    // partial=true -> still running (is_final = false); partial=false -> final.
    conditions.push('is_final = $isFinal');
    params.isFinal = !options.partial;
  }
  const cteSql = `
    WITH purchase_totals AS (
      SELECT
        p.id,
        p.listing_id,
        l.title AS listing_title,
        p.status,
        p.price_paid,
        p.purchase_date,
        -- Every Sale row implies its Part is already 'sold': createSale
        -- itself only inserts the sales row (see sales.ts), but every
        -- caller (routes/sales.ts's POST /api/parts/:partId/sale) pairs it
        -- with an updatePart(... status: 'sold') in the same request, so
        -- this LEFT JOIN naturally only pulls realized sales — no extra
        -- status filter needed.
        COUNT(parts.id) AS total_parts,
        COUNT(parts.id) FILTER (WHERE parts.status IN ('sold', 'unsellable')) AS parts_resolved,
        COALESCE(SUM(s.sold_price), 0) AS sale_revenue,
        COALESCE(SUM(s.platform_fee), 0) + COALESCE(SUM(s.shipping_cost), 0) AS fees_and_shipping
      FROM purchases p
      JOIN listings l ON l.id = p.listing_id
      LEFT JOIN parts ON parts.purchase_id = p.id
      LEFT JOIN sales s ON s.part_id = parts.id
      GROUP BY p.id, p.listing_id, l.title, p.status, p.price_paid, p.purchase_date
    ),
    profit AS (
      SELECT
        *,
        (sale_revenue - fees_and_shipping - price_paid) AS net_profit,
        (total_parts > 0 AND parts_resolved = total_parts) AS is_final
      FROM purchase_totals
    )
  `;
  const whereSql = conditions.length > 0 ? `WHERE ${conditions.join(' AND ')}` : '';
  return { cteSql, whereSql, params };
}

/**
 * Lists the per-Purchase profit rollup (Req 10), filtered by status and/or
 * partial-vs-final, sorted by the requested column, and paginated (Req 11,
 * 15) — the aggregated dashboard, distinct from listPurchasesWithListingSummary's
 * simpler per-purchase browsing list.
 */
export async function listProfitByPurchase(options?: ListProfitOptions): Promise<PurchaseProfit[]> {
  const connection = await getConnection();
  const { cteSql, whereSql, params } = buildProfitQuery(options);
  const sortColumn = SORT_COLUMN[options?.sortBy ?? 'purchaseDate'];
  const sortDir = options?.sortDir === 'asc' ? 'ASC' : 'DESC';
  const reader = await connection.runAndReadAll(
    `${cteSql}
     SELECT * FROM profit
     ${whereSql}
     ORDER BY ${sortColumn} ${sortDir}, id ASC
     LIMIT $limit OFFSET $offset`,
    { ...params, limit: options?.limit ?? 20, offset: options?.offset ?? 0 },
  );
  return reader.getRowObjectsJson().map(mapRow);
}

/** Counts Purchases matching the same status/partial filter as listProfitByPurchase, so the Profit dashboard (Req 11, 15) can paginate against an accurate total. */
export async function countProfitByPurchase(options?: Pick<ListProfitOptions, 'status' | 'partial'>): Promise<number> {
  const connection = await getConnection();
  const { cteSql, whereSql, params } = buildProfitQuery(options);
  const reader = await connection.runAndReadAll(`${cteSql} SELECT count(*) AS total FROM profit ${whereSql}`, params);
  return Number(reader.getRowObjectsJson()[0].total);
}
