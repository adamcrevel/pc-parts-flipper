// Profit dashboard HTTP types (Req 10-11, 15) — the aggregated, per-Purchase
// profit rollup, sortable/filterable/paginated. Lives here (not apps/server)
// because apps/web may never import apps/server directly (standing check);
// mirrors apps/server/src/db/queries/profit.ts's PurchaseProfit shape.
import type { PurchaseStatus } from './purchases.js';

/** Columns the Profit dashboard can sort by (Req 11). */
export type ProfitSortBy = 'netProfit' | 'pricePaid' | 'purchaseDate';

/** Sort direction for the Profit dashboard (Req 11). */
export type ProfitSortDir = 'asc' | 'desc';

/**
 * One row of the Profit dashboard (Req 10): a Purchase's price paid,
 * realized sale revenue, fees/shipping across those sales, and the
 * resulting net profit (= sale revenue - fees/shipping - price paid).
 * Per-part cost is never allocated (assumption A1) — every figure here is
 * at the Purchase/lot level only. `isFinal` is false ("partial"/running)
 * until every Part generated by this Purchase's teardown is either sold or
 * unsellable; a Purchase with no Parts yet (not torn down) is also partial.
 */
export interface PurchaseProfit {
  purchaseId: string;
  listingId: string;
  listingTitle: string;
  status: PurchaseStatus;
  pricePaid: number;
  purchaseDate: string;
  saleRevenue: number;
  feesAndShipping: number;
  netProfit: number;
  totalParts: number;
  partsResolved: number;
  isFinal: boolean;
}

/** `GET /api/purchases/profit` response: one page of PurchaseProfit rows plus the total matching count, so apps/web can paginate without an unbounded fetch (Req 11, 15). */
export interface ListProfitResponse {
  purchases: PurchaseProfit[];
  total: number;
}
